class TargetTest(unittest.TestCase):
    def test_short_and_url_forms(self):
        self.assertEqual(str(parse(["crispin-lab/citadel-be#12"]).target), "crispin-lab/citadel-be#12")
        url = "https://github.com/crispin-lab/citadel-fe/pull/7/files"
        self.assertEqual(parse([url]).target.number, 7)

    def test_other_owner_is_rejected(self):
        with self.assertRaises(ArgsError):
            parse(["someone/repo#1"])

    def test_unknown_flag_and_focus(self):
        with self.assertRaises(ArgsError):
            parse(["crispin-lab/x#1", "--with-codex"])
        with self.assertRaises(ArgsError):
            parse(["crispin-lab/x#1", "--focus", "style"])
        self.assertEqual(parse(["crispin-lab/x#1", "--focus", "security,tests"]).focus, ["security", "tests"])

    def test_command_must_be_first_line(self):
        target = Target("crispin-lab", "x", 1)
        self.assertIsNone(parse_command("다음에 /pcr 로 다시 돌려 볼게요", target))
        self.assertIsNone(parse_command("/pcrx", target))
        options = parse_command("/pcr --reply --dry-run\n추가 설명", target)
        self.assertTrue(options.reply and options.dry_run)
        self.assertEqual(options.target, target)

    def test_command_cannot_switch_target(self):
        with self.assertRaises(ArgsError):
            parse_command("/pcr crispin-lab/other#9", Target("crispin-lab", "x", 1))


