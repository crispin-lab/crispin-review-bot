class SanitizeTest(unittest.TestCase):
    def test_footer_lines_are_stripped(self):
        body = "지적입니다.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"
        self.assertEqual(sanitize(body), "지적입니다.\n")

    def test_co_author_and_robot_lines_are_stripped(self):
        body = "본문\nCo-Authored-By: Someone <a@b.c>\n\N{ROBOT FACE} Generated with tooling\n"
        self.assertEqual(sanitize(body), "본문\n")

    def test_inline_attribution_is_rejected(self):
        for body in ["이 리뷰는 AI 가 생성한 내용입니다.", "This is AI-generated feedback.", "Claude 가 작성한 답글"]:
            with self.assertRaises(AttributionError, msg=body):
                sanitize(body)

    def test_secret_like_strings_are_rejected(self):
        secrets = [
            "ghp_" + "a" * 36,
            "github_pat_" + "b" * 60,
            "sk-ant-oat01-" + "c" * 40,
            "eyJhbGciOiJSUzI1NiJ9.eyJzdWIiOiJyZXBvOngifQ.c2lnbmF0dXJlc2lnbmF0dXJl",
        ]
        for secret in secrets:
            with self.assertRaises(SecretLeakError, msg=secret[:12]):
                sanitize(f"환경 변수 값: {secret}")

    def test_normal_review_text_passes(self):
        body = "`claude -p` 호출에 `--bare` 를 주면 OAuth 를 읽지 않습니다.\n\n<!-- pcr:0123456789ab -->"
        self.assertEqual(sanitize(body), body + "\n")


class FingerprintTest(unittest.TestCase):
    def test_whitespace_and_case_do_not_change_fingerprint(self):
        self.assertEqual(
            finding_fingerprint("src/A.ts", 3, "Foo  bar\nbaz"),
            finding_fingerprint("src/a.ts", 3, "foo bar baz"),
        )

    def test_line_changes_fingerprint(self):
        self.assertNotEqual(finding_fingerprint("a", 1, "x"), finding_fingerprint("a", 2, "x"))

    def test_markers_round_trip(self):
        fp = summary_fingerprint(42, "abc")
        text = f"본문\n<!-- pcr:{fp} -->\n<!-- pcr:reply -->"
        self.assertEqual(markers_in(text), {fp})
        self.assertEqual(strip_markers(text), "본문")


