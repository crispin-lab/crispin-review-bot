class ReplyFilterTest(unittest.TestCase):
    def thread(self, *authors, resolved=False):
        nodes = [{"author": {"login": login}} for login in authors]
        return {"isResolved": resolved, "comments": {"nodes": nodes}}

    def test_loop_guard(self):
        bots = ["crispin-bot"]
        self.assertTrue(_keep(self.thread("crispin-bot", "crispin"), bots))
        self.assertFalse(_keep(self.thread("crispin-bot", "crispin", "crispin-bot"), bots))
        self.assertFalse(_keep(self.thread("crispin", "crispin-bot"), bots))
        self.assertFalse(_keep(self.thread("crispin-bot", "crispin", resolved=True), bots))


class SummaryTest(unittest.TestCase):
    def context(self, **overrides):
        base = dict(
            owner="crispin-lab", repo="x", number=1, title="t", body="", author="a", head_sha="abcdef1234",
            base_ref="main", head_ref="f", state="open", draft=False, additions=3, deletions=1,
            changed_files=2, files=[], linked_issues=[], bot_logins=["crispin-bot"], prior_fingerprints=[],
            prior_findings=[], conventions="", convention_files=[],
        )
        base.update(overrides)
        return Context(**base)

    def test_sections_order_and_empty_sections_omitted(self):
        raw = {"scope": "설정 화면 추가.", "risks": [], "themes": []}
        body = review._summary(self.context(), raw, [], [], None, "run1")
        self.assertNotIn("## Risks", body)
        self.assertNotIn("## Themes", body)
        self.assertLess(body.index("## Scope"), body.index("## Conventions"))
        self.assertLess(body.index("## Conventions"), body.index("## Dedup"))
        self.assertIn("새로운 지적 사항이 없습니다", body)
        self.assertIn("<!-- pcr-run:run1 -->", body)

    def test_unplaced_findings_go_to_risks(self):
        finding = review.Finding("a.ts", 99, "correctness", "문제", None, "f" * 12)
        raw = {"scope": "s", "risks": ["위험"], "themes": ["패턴"]}
        body = review._summary(self.context(), raw, [], [finding], None, "run1")
        risks = body[body.index("## Risks") : body.index("## Themes")]
        self.assertIn("`a.ts:99` — 문제", risks)
        self.assertIn(review.UNPLACED, risks)

    def test_placeholder_sits_between_scope_and_themes(self):
        raw = {"scope": "s", "risks": [], "themes": ["패턴"]}
        body = review._summary(self.context(), raw, [], [], None, "run1")
        self.assertLess(body.index(review.UNPLACED), body.index("## Themes"))


